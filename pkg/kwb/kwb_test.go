func TestConcurrentReadsUpdatesAndCancellation(t *testing.T) {
	root := t.TempDir()
	index := filepath.Join(t.TempDir(), "index")
	writer := testService(t, root, index, nil)
	reader := testService(t, root, index, nil)
	writeFixture(t, root, "doc.md", "shared orchard\n")
	buildFixture(t, writer, root)
	var wg sync.WaitGroup
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for j := 0; j < 20; j++ {
				result, err := reader.Search(t.Context(), SearchOptions{
					Query: "orchard",
				})
				if err != nil || result.Total != 1 {
					t.Errorf("concurrent search: %+v %v", result, err)
					return
				}
			}
		}()
	}
	for i := 0; i < 3; i++ {
		writeFixture(t, root, "doc.md", fmt.Sprintf("shared orchard revision %d\n", i))
		buildFixture(t, writer, root)
	}
	wg.Wait()
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	if _, err := reader.Search(ctx, SearchOptions{
		Query: "orchard",
	}); !errors.Is(err, context.Canceled) {
		t.Fatalf("search cancellation: %v", err)
	}
	if _, err := reader.ListFiles(ctx, ListOptions{}); !errors.Is(err, context.Canceled) {
		t.Fatalf("list cancellation: %v", err)
	}
	if _, err := reader.GetFile(ctx, "doc.md", 1, 2); !errors.Is(err, context.Canceled) {
		t.Fatalf("read cancellation: %v", err)
	}
	fastTimeout := testService(t, root, index, func(s *Settings) { s.SearchTimeout = time.Nanosecond })
	if _, err := fastTimeout.Search(
		t.Context(),
		SearchOptions{
			Query: "orchard",
		},
	); !errors.Is(
		err,
		context.DeadlineExceeded,
	) {
		t.Fatalf("timeout was ignored: %v", err)
	}
}

