func TestCrossProcessPublication(t *testing.T) {
	root := t.TempDir()
	index := filepath.Join(t.TempDir(), "index")
	reader := testService(t, root, index, nil)
	writeFixture(t, root, "doc.md", "original orchard")
	buildFixture(t, reader, root)
	before, err := reader.GetStats(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	for _, full := range []string{"0", "1"} {
		writeFixture(t, root, "doc.md", "updated orchard "+full)
		ctx, cancel := context.WithTimeout(t.Context(), 15*time.Second)
		command := exec.CommandContext(ctx, os.Args[0], "-test.run=^TestIndexBuildProcess$")
		command.Env = append(
			os.Environ(),
			"KWB_BUILD_HELPER=1",
			"KWB_BUILD_ROOT="+root,
			"KWB_BUILD_INDEX="+index,
			"KWB_BUILD_FULL="+full,
		)
		output, err := command.CombinedOutput()
		cancel()
		if err != nil {
			t.Fatalf("building while reader is open: %v\n%s", err, output)
		}
		if _, err := os.Stat(filepath.Join(index, before.Generation)); err != nil {
			t.Fatalf("active reader generation removed: %v", err)
		}
		result, err := reader.Search(t.Context(), SearchOptions{
			Query: "updated",
		})
		if err != nil || result.Total != 1 || result.Generation == before.Generation {
			t.Fatalf("reader did not refresh: %+v %v", result, err)
		}
		before, err = reader.GetStats(t.Context())
		if err != nil {
			t.Fatal(err)
		}
	}
}

