func writeFixture(t testing.TB, root, path, content string) {
	t.Helper()
	path = filepath.Join(root, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
}

func testService(t testing.TB, root, index string, configure func(*Settings)) *Service {
	t.Helper()
	settings := NewSettings()
	settings.RootPath, settings.IndexPath = root, index
	if configure != nil {
		configure(settings)
	}
	service, err := NewService(settings)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := service.Close(); err != nil {
			t.Error(err)
		}
	})
	return service
}

func buildFixture(t testing.TB, service *Service, root string) BuildResult {
	t.Helper()
	report, err := service.BuildIndex(t.Context(), root)
	if err != nil {
		t.Fatal(err)
	}
	return report
}

func TestFilteringAndIncrementalUpdates(t *testing.T) {
	root := t.TempDir()
	index := filepath.Join(root, "search-index")
	for path, content := range map[string]string{
		".gitignore":      "ignored/\n*.secret\nnotes/*\n!notes/keep.md\n/anchored.md\n",
		"README.md":       "# Orchard\nnectarine planting\n",
		"service.go":      "package example\nfunc OriginalSymbol() {}\nfunc RemovedSymbol() {}\n",
		"ignored/skip.go": "package skip", "notes/skip.md": "skip", "notes/keep.md": "keep",
		"nested/.gitignore": "*.md\n!keep.md\n", "nested/skip.md": "skip", "nested/keep.md": "keep",
		"anchored.md": "skip", "other/anchored.md": "keep",
		".tools/artifact.md": "skip", ".build/artifact.go": "package skip",
		"custom/skip.md": "skip", "visible.secret": "skip",
		"extra.xyz": "custom extension", "Dockerfile": "FROM scratch", ".env": "APP_MODE=example",
		"generated.go": "// Code generated by generator. DO NOT EDIT.\npackage example\n",
		"go.sum":       "skip", "package-lock.json": "{}", "binary.md": "a\x00b", "huge.md": strings.Repeat("x", 1025),
	} {
		writeFixture(t, root, path, content)
	}
	service := testService(t, root, index, func(s *Settings) {
		s.ExtraExtensions = []string{".xyz"}
		s.ExcludeDirs = []string{"custom"}
		s.MaxFileSize = 1024
		s.BatchSize = 2
	})
	report := buildFixture(t, service, root)
	want := []string{
		".env",
		".gitignore",
		sourceIgnorePath,
		"Dockerfile",
		"README.md",
		"extra.xyz",
		"nested/.gitignore",
		"nested/keep.md",
		"notes/keep.md",
		"other/anchored.md",
		"service.go",
	}
	page, err := service.ListFiles(t.Context(), ListOptions{})
	if err != nil {
		t.Fatal(err)
	}
	var paths []string
	for _, file := range page.Files {
		paths = append(paths, file.Path)
	}
	if !slices.Equal(paths, want) {
		t.Fatalf("indexed paths = %v, want %v", paths, want)
	}
	if report.Indexed != len(want) || !report.Rebuilt {
		t.Fatalf("initial report: %+v", report)
	}
	generation := page.Generation
	// The index is inside the source root; repeated builds must not index its files.
	report = buildFixture(t, service, root)
	if report.Indexed != 0 || report.Deleted != 0 || report.Unchanged != len(want) || report.Rebuilt {
		t.Fatalf("no-op report: %+v", report)
	}
	stats, err := service.GetStats(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	if stats.Generation != generation {
		t.Fatal("no-op build published a generation")
	}
	writeFixture(t, root, "service.go", "package example\nfunc ReplacementSymbol() {}\n")
	if err := os.Remove(filepath.Join(root, "README.md")); err != nil {
		t.Fatal(err)
	}
	writeFixture(t, root, "new.md", "# Fresh\napricot planting")
	report = buildFixture(t, service, root)
	if report.Indexed != 2 || report.Deleted != 1 || report.Unchanged != len(want)-2 {
		t.Fatalf("incremental report: %+v", report)
	}
	for _, word := range []string{"OriginalSymbol", "RemovedSymbol", "nectarine"} {
		result, err := service.Search(t.Context(), SearchOptions{
			Query: word,
		})
		if err != nil {
			t.Fatal(err)
		}
		if result.Total != 0 {
			t.Fatalf("stale content for %s: %+v", word, result)
		}
	}
	result, err := service.Search(t.Context(), SearchOptions{
		Query: "ReplacementSymbol",
	})
	if err != nil || result.Total != 1 {
		t.Fatalf("new content missing: %+v, %v", result, err)
	}
	// Hashes detect edits even when file size and modification time are unchanged.
	file := filepath.Join(root, "new.md")
	info, err := os.Stat(file)
	if err != nil {
		t.Fatal(err)
	}
	writeFixture(t, root, "new.md", "# Fresh\npeaches planting")
	if err := os.Chtimes(file, info.ModTime(), info.ModTime()); err != nil {
		t.Fatal(err)
	}
	if report := buildFixture(t, service, root); report.Indexed != 1 {
		t.Fatalf("same-time edit ignored: %+v", report)
	}
	writeFixture(t, root, ".gitignore", "ignored/\n*.secret\nnotes/*\n!notes/keep.md\n/anchored.md\nnew.md\n")
	if report := buildFixture(t, service, root); report.Deleted != 1 {
		t.Fatalf("ignore change did not remove file: %+v", report)
	}
}

func TestChunkRankingAndRanges(t *testing.T) {
	root := t.TempDir()
	service := testService(t, root, filepath.Join(t.TempDir(), "index"), nil)
	writeFixture(
		t,
		root,
		"server.go",
		"package example\n\n// NewHTTPServer configures the listener.\nfunc NewHTTPServer() {}\n\nfunc Unrelated() {}\n",
	)
	writeFixture(
		t,
		root,
		"guide.md",
		"# Setup\nGeneral introduction.\n\n## HTTP server\nSet the listener port.\n\n## Storage\nConfigure the database.\n",
	)
	writeFixture(t, root, "config.json", "{\"http_server_port\": 8080}\n")
	writeFixture(t, root, "mentions.md", "# Notes\nNewHTTPServer is mentioned incidentally here.\n")
	buildFixture(t, service, root)
	for _, tc := range []struct {
		query, kind, language, path string
		line                        int
	}{
		{"NewHTTPServer", "", "", "server.go", 3},
		{"http server", "code", "go", "server.go", 3},
		{"HTTP server", "documentation", "", "guide.md", 4},
		{"8080", "config", "json", "config.json", 1},
		{"http_server_port", "config", "json", "config.json", 1},
	} {
		t.Run(tc.query+tc.kind, func(t *testing.T) {
			result, err := service.Search(
				t.Context(),
				SearchOptions{
					Query:    tc.query,
					Kind:     tc.kind,
					Language: tc.language,
				},
			)
			if err != nil {
				t.Fatal(err)
			}
			if len(result.Results) == 0 {
				t.Fatalf("no results for %q", tc.query)
			}
			hit := result.Results[0]
			if hit.Path != tc.path || hit.StartLine != tc.line {
				t.Fatalf("top hit: %+v", hit)
			}
			if strings.Contains(hit.Snippet, "<mark>") || len(hit.Snippet) > 2000 {
				t.Fatalf("invalid snippet: %q", hit.Snippet)
			}
			content, err := service.GetFile(t.Context(), hit.Path, hit.StartLine, hit.EndLine)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(content.Content, hit.Snippet) {
				t.Fatalf("snippet does not match source lines: %+v, %+v", hit, content)
			}
		})
	}
	result, err := service.Search(t.Context(), SearchOptions{
		Query:      "server",
		PathPrefix: "guide",
	})
	if err != nil || len(result.Results) != 1 || result.Results[0].Path != "guide.md" {
		t.Fatalf("prefix filter: %+v %v", result, err)
	}
	// Fenced headings stay inside their containing documentation section.
	docs := chunkFile("test.md", []byte("# Real\n```md\n# Example\n```\n## Next\nbody\n"))
	if len(docs) != 2 || docs[0].Title != "Real" || docs[1].Title != "Real > Next" {
		t.Fatalf("Markdown sections: %+v", docs)
	}
	long := chunkFile("long.md", []byte(strings.Repeat("long content\n", 300)))
	for _, doc := range long {
		if doc.EndLine-doc.StartLine+1 > maxChunkLines || len(doc.Content) > maxChunkBytes {
			t.Fatal("unbounded chunk")
		}
	}
	broken := chunkFile("broken.go", []byte("package example\nfunc Editing(\n"))
	if len(broken) == 0 {
		t.Fatal("incomplete Go source was discarded")
	}
}

func TestPaginationAndFileReading(t *testing.T) {
	root := t.TempDir()
	service := testService(t, root, filepath.Join(t.TempDir(), "index"), nil)
	for i := 0; i < 1051; i++ {
		writeFixture(t, root, fmt.Sprintf("docs/%04d.md", i), "# Orchard\napricot farming\n")
	}
	writeFixture(t, root, "long.md", strings.Repeat("orchard\n", 650))
	buildFixture(t, service, root)
	var paths []string
	for offset := 0; ; {
		page, err := service.ListFiles(t.Context(), ListOptions{
			Limit:  113,
			Offset: offset,
		})
		if err != nil {
			t.Fatal(err)
		}
		if page.Total != 1053 {
			t.Fatalf("total=%d", page.Total)
		}
		for _, file := range page.Files {
			paths = append(paths, file.Path)
		}
		if page.NextOffset == nil {
			break
		}
		offset = *page.NextOffset
	}
	if len(paths) != 1053 || len(slices.Compact(paths)) != 1053 {
		t.Fatal("pagination lost or duplicated files")
	}
	first, err := service.Search(t.Context(), SearchOptions{
		Query: "apricot",
		Limit: 17,
	})
	if err != nil || first.NextOffset == nil {
		t.Fatalf("first page: %+v %v", first, err)
	}
	second, err := service.Search(t.Context(), SearchOptions{
		Query:  "apricot",
		Limit:  17,
		Offset: *first.NextOffset,
	})
	if err != nil {
		t.Fatal(err)
	}
	if first.Total != 1051 || first.Results[0].Path == second.Results[0].Path {
		t.Fatal("invalid search pagination")
	}
	content, err := service.GetFile(t.Context(), "long.md", 0, 0)
	if err != nil {
		t.Fatal(err)
	}
	if content.StartLine != 1 || content.EndLine != 200 || content.NextStartLine == nil ||
		*content.NextStartLine != 201 ||
		content.TotalLines != 650 {
		t.Fatalf("range: %+v", content)
	}
	content, err = service.GetFile(t.Context(), "long.md", 640, 700)
	if err != nil || content.EndLine != 650 || content.NextStartLine != nil {
		t.Fatalf("last range: %+v %v", content, err)
	}
	for _, path := range []string{"../outside.md", filepath.Join(t.TempDir(), "outside.md")} {
		if _, err := service.GetFile(t.Context(), path, 1, 10); err == nil {
			t.Fatal("file outside root was accepted")
		}
	}
	if _, err := service.GetFile(t.Context(), "long.md", 1, 501); err == nil {
		t.Fatal("oversized range accepted")
	}
	if _, err := service.Search(t.Context(), SearchOptions{
		Query: "orchard",
		Limit: MaxSearchLimit + 1,
	}); err == nil {
		t.Fatal("oversized search accepted")
	}
	if _, err := service.ListFiles(t.Context(), ListOptions{
		Offset: -1,
	}); err == nil {
		t.Fatal("negative offset accepted")
	}
}

