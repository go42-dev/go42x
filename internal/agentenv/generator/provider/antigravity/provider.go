package antigravity

import (
	"fmt"
	"log/slog"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"

	"github.com/go42-dev/go42x/internal/agentenv/generator/provider"
	"github.com/go42-dev/go42x/internal/fspatch"
)

const (
	Name      = "antigravity"
	PluginDir = ".agents/plugins/project-tools"
)

var antigravityEnvNamePattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// PluginManifest identifies the generated workspace plugin.
// @see https://antigravity.google/docs/plugins
type PluginManifest struct {
	Schema      string `json:"$schema"`
	Name        string `json:"name"`
	Description string `json:"description"`
}

// MCPConfig represents the plugin's mcp_config.json.
type MCPConfig struct {
	MCPServers map[string]MCPServer `json:"mcpServers"`
}

// MCPServer describes an MCP server in Antigravity's plugin configuration.
// @see https://antigravity.google/docs/mcp
type MCPServer struct {
	ServerURL string            `json:"serverUrl,omitempty"`
	Command   string            `json:"command,omitempty"`
	Args      []string          `json:"args,omitempty"`
	Env       map[string]string `json:"env,omitempty"`
	CWD       string            `json:"cwd,omitempty"`
	Headers   map[string]string `json:"headers,omitempty"`
}

// Settings contains the inputs needed to generate this provider's files.
type Settings struct {
	OutputDir  string
	MCPServers map[string]provider.MCPServer
}

type Provider struct {
	settings Settings
}

func New(
	_ *slog.Logger,
	_ provider.TemplateEngineAccessor,
	settings Settings,
	_ string,
) *Provider {
	return &Provider{settings: settings}
}

func (p *Provider) Prepare(plan *fspatch.Plan, _ map[string]any) error {
	if err := p.prepareConfigFiles(plan); err != nil {
		return fmt.Errorf("failed to prepare config files: %w", err)
	}

	return nil
}

func (p *Provider) prepareConfigFiles(plan *fspatch.Plan) error {
	pluginDir := filepath.Join(p.settings.OutputDir, PluginDir)
	manifest := PluginManifest{
		Schema:      "https://antigravity.google/schemas/v1/plugin.json",
		Name:        "project-tools",
		Description: "Project MCP tools generated by go42x.",
	}
	manifestPath := filepath.Join(pluginDir, "plugin.json")
	if err := provider.PrepareJSONFile(plan, manifestPath, manifest); err != nil {
		return fmt.Errorf("failed to prepare %s: %w", manifestPath, err)
	}

	servers := make(map[string]MCPServer)
	for _, name := range slices.Sorted(maps.Keys(p.settings.MCPServers)) {
		server := p.settings.MCPServers[name]
		if !server.Enabled {
			continue
		}

		var entry MCPServer
		if server.Transport() == provider.MCPServerTypeStdio {
			entry.Command = server.Command
			entry.Args = server.Args
			entry.Env = server.Env
			entry.CWD = server.CWD
		} else {
			entry.ServerURL = server.URL
			headers, err := resolveAntigravityHeaders(server.Headers)
			if err != nil {
				return fmt.Errorf("MCP server %s: %w", name, err)
			}

			entry.Headers = headers
		}

		servers[name] = entry
	}

	mcpPath := filepath.Join(pluginDir, "mcp_config.json")
	if err := provider.PrepareJSONFile(plan, mcpPath, MCPConfig{MCPServers: servers}); err != nil {
		return fmt.Errorf("failed to prepare %s: %w", mcpPath, err)
	}

	return nil
}

// resolveAntigravityHeaders expands references before writing Antigravity's local
// configuration, which sends header values literally. Expansion errors never
// include header values.
func resolveAntigravityHeaders(headers map[string]string) (map[string]string, error) {
	resolved := make(map[string]string, len(headers))
	for _, key := range slices.Sorted(maps.Keys(headers)) {
		var expansionErr error
		lookupEnv := func(name string) string {
			if expansionErr != nil {
				return ""
			}
			if !antigravityEnvNamePattern.MatchString(name) {
				expansionErr = fmt.Errorf("unsupported environment reference syntax; use $NAME or ${NAME}")
				return ""
			}

			value, exists := os.LookupEnv(name)
			if !exists || len(value) == 0 {
				expansionErr = fmt.Errorf("environment variable %q is unset or empty", name)
				return ""
			}

			return value
		}

		value := os.Expand(headers[key], lookupEnv)
		if expansionErr != nil {
			return nil, fmt.Errorf("header %s: %w", key, expansionErr)
		}
		resolved[key] = value
	}

	return resolved, nil
}

// MCPToolName formats a server tool name for this provider.
func MCPToolName(serverName, toolName string) string {
	return serverName + "/" + toolName
}
