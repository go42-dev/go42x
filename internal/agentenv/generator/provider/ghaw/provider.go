package ghaw

import (
	"bytes"
	"fmt"
	"log/slog"
	"maps"
	"path/filepath"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/go42-dev/go42x/internal/agentenv/generator/provider"
	"github.com/go42-dev/go42x/internal/fspatch"
)

const (
	Name                = "gh-aw"
	MCPFile             = ".github/workflows/900-aw-mcp.md"
	ghAWMCPDescription  = "Generated by go42x from .go42x/go42x.yaml; import this MCP configuration into agentic workflows."
	ghAWFrontmatter     = "---\n"
	ghAWGitHubToken     = "GITHUB_TOKEN"        // #nosec G101 -- Environment variable name, not a credential.
	ghAWGitHubTokenExpr = "${{ github.token }}" // #nosec G101 -- Workflow expression, not a credential.
	ghAWCommandDocker   = "docker"
	ghAWCommandNPX      = "npx"
	ghAWCommandUVX      = "uvx"
	ghAWWorkDirFlag     = "--workdir"
)

var (
	ghAWServerNamePattern = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)
	ghAWEnvPattern        = regexp.MustCompile(`\$\{[A-Za-z_][A-Za-z0-9_]*\}|\$[A-Za-z_][A-Za-z0-9_]*`)
	ghAWEnvNamePattern    = regexp.MustCompile(`^[A-Z_][A-Z0-9_]*$`)
	ghAWHeaderPattern     = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)
)

// MCPConfig is an importable workflow fragment, without triggers or an engine.
type MCPConfig struct {
	Description string               `yaml:"description"`
	MCPServers  map[string]MCPServer `yaml:"mcp-servers"`
}

// MCPServer contains the fields supported by gh-aw's MCP declarations.
// @see https://github.github.com/gh-aw/guides/mcps/
type MCPServer struct {
	Container      string            `yaml:"container,omitempty"`
	Version        string            `yaml:"version,omitempty"`
	Entrypoint     string            `yaml:"entrypoint,omitempty"`
	EntrypointArgs []string          `yaml:"entrypointArgs,omitempty"`
	Mounts         []string          `yaml:"mounts,omitempty"`
	Type           string            `yaml:"type"`
	Command        string            `yaml:"command,omitempty"`
	Args           []string          `yaml:"args,omitempty"`
	Env            map[string]string `yaml:"env,omitempty"`
	URL            string            `yaml:"url,omitempty"`
	Headers        map[string]string `yaml:"headers,omitempty"`
	Allowed        []string          `yaml:"allowed"`
}

// Settings contains the inputs needed to generate this provider's files.
type Settings struct {
	OutputDir  string
	MCPServers map[string]provider.MCPServer
}

type Provider struct {
	settings Settings
}

func New(
	_ *slog.Logger,
	settings Settings,
	_ provider.TemplateEngineAccessor,
	_ string,
) *Provider {
	return &Provider{settings: settings}
}

func (p *Provider) Prepare(plan *fspatch.Plan, _ map[string]any) error {
	fragment := MCPConfig{
		Description: ghAWMCPDescription,
		MCPServers:  make(map[string]MCPServer),
	}
	for name, server := range p.settings.MCPServers {
		if !server.Enabled {
			continue
		}

		if !ghAWServerNamePattern.MatchString(name) {
			return fmt.Errorf(
				"MCP server %s: gh-aw requires names containing only letters, digits, underscores, or hyphens",
				name,
			)
		}
		container := server.Container
		// Adapt a copy; other providers keep the shared runner command and environment.
		if container != nil {
			if server.Transport() != provider.MCPServerTypeStdio {
				return fmt.Errorf("MCP server %s: container requires a stdio server", name)
			}
			server.Command = ghAWCommandDocker
			server.Args = nil
			env := make(map[string]string, len(server.Env)+len(container.Env))
			maps.Copy(env, server.Env)
			maps.Copy(env, container.Env)
			server.Env = env
		}
		entry, err := ghAWMCPServer(server)
		if err != nil {
			return fmt.Errorf("MCP server %s: %w", name, err)
		}
		if container != nil {
			entry.Command = ""
			entry.Container = ghAWExpression(container.Image)
			entry.Version = ghAWExpression(container.Version)
			entry.Entrypoint = ghAWExpression(container.Command)
			for _, arg := range container.Args {
				entry.EntrypointArgs = append(entry.EntrypointArgs, ghAWExpression(arg))
			}
			// Native mount paths use GitHub Actions expressions, not secret references.
			entry.Mounts = container.Mounts
			if len(container.WorkDir) > 0 {
				entry.Args = []string{ghAWWorkDirFlag, container.WorkDir}
			}
		}
		fragment.MCPServers[name] = entry
	}

	var content bytes.Buffer
	content.WriteString(ghAWFrontmatter)
	encoder := yaml.NewEncoder(&content)
	encoder.SetIndent(2)
	if err := encoder.Encode(fragment); err != nil {
		return fmt.Errorf("failed to encode gh-aw MCP declarations: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return fmt.Errorf("failed to close gh-aw MCP declarations: %w", err)
	}
	content.WriteString(ghAWFrontmatter)

	if err := plan.Write(
		filepath.Join(p.settings.OutputDir, MCPFile),
		content.Bytes(),
		fspatch.Settings,
		false,
	); err != nil {
		return fmt.Errorf("failed to prepare %s: %w", MCPFile, err)
	}
	return nil
}

func ghAWMCPServer(server provider.MCPServer) (MCPServer, error) {
	entry := MCPServer{
		Type:    server.Transport(),
		Allowed: []string{"*"},
	}
	if len(server.CWD) > 0 {
		return entry, fmt.Errorf("gh-aw does not support cwd")
	}

	switch server.Transport() {
	case provider.MCPServerTypeStdio:
		switch server.Command {
		case ghAWCommandDocker, ghAWCommandNPX, ghAWCommandUVX:
		default:
			return entry, fmt.Errorf(
				"gh-aw cannot run this stdio command directly; configure a container or use docker, npx, uvx",
			)
		}
		entry.Command = ghAWExpression(server.Command)
		for _, arg := range server.Args {
			entry.Args = append(entry.Args, ghAWExpression(arg))
		}
		entry.Env = make(map[string]string, len(server.Env))
		for name, value := range server.Env {
			if !ghAWEnvNamePattern.MatchString(name) {
				return entry, fmt.Errorf(
					"gh-aw requires environment variable names containing only uppercase letters, digits, or underscores",
				)
			}
			entry.Env[name] = ghAWExpression(value)
		}
	case provider.MCPServerTypeHTTP:
		if len(server.Env) > 0 {
			return entry, fmt.Errorf("gh-aw does not support env for HTTP servers; use headers")
		}
		entry.URL = ghAWExpression(server.URL)
		entry.Headers = make(map[string]string, len(server.Headers))
		for name, value := range server.Headers {
			if !ghAWHeaderPattern.MatchString(name) {
				return entry, fmt.Errorf(
					"gh-aw requires HTTP header names containing only letters, digits, underscores, or hyphens",
				)
			}
			entry.Headers[name] = ghAWExpression(value)
		}
	default:
		return entry, fmt.Errorf("gh-aw supports only stdio and HTTP transports")
	}
	return entry, nil
}

// ghAWExpression preserves references without reading the local environment.
func ghAWExpression(value string) string {
	return ghAWEnvPattern.ReplaceAllStringFunc(value, func(reference string) string {
		name := strings.Trim(strings.TrimPrefix(reference, "$"), "{}")
		if name == ghAWGitHubToken {
			return ghAWGitHubTokenExpr
		}
		return "${{ secrets." + name + " }}"
	})
}

// MCPToolName formats a server tool name for this provider.
func MCPToolName(_, toolName string) string {
	return toolName
}
